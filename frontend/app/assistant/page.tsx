"use client";

import { useRef, useState } from "react";
import { Sidebar } from "@/components/Sidebar";

const API_BASE =
  process.env.NEXT_PUBLIC_API_URL || "http://127.0.0.1:8010";

interface Source {
  excerpt?: string;
  document_id?: number;
  chunk_index?: number;
  page_number?: number | null;
  filename?: string;
  relevance_score?: number;
  [key: string]: unknown;
}

interface Message {
  role: "user" | "assistant";
  text: string;
  sources?: Source[];
}

interface ApiResponse {
  sources?: unknown;
  answer_grounding?: unknown;
  answer?: unknown;
  message?: unknown;
  detail?: unknown;
}

interface UploadResponse {
  filename?: string;
  chunks_indexed?: number;
  pages_processed?: number;
  detail?: unknown;
}

function getErrorMessage(
  data: ApiResponse,
  status: number
): string {
  if (typeof data.detail === "string") {
    return data.detail;
  }

  if (Array.isArray(data.detail)) {
    return data.detail
      .map((item) =>
        typeof item === "object" &&
        item !== null &&
        "msg" in item
          ? String(item.msg)
          : JSON.stringify(item)
      )
      .join("; ");
  }

  if (status === 401) {
    return "Your login session has expired. Please log in again.";
  }

  if (status === 403) {
    return "You do not have permission to perform this action. Sign in with an admin account to upload PDFs.";
  }

  return `Request failed with status ${status}`;
}

export default function AssistantPage() {
  const [messages, setMessages] = useState<Message[]>([
    {
      role: "assistant",
      text:
        "Ask me about uploaded planning guidelines, traffic rules, " +
        "or disaster manuals. I'll generate answers using Ollama " +
        "and relevant document passages, with supporting sources.",
    },
  ]);

  const [input, setInput] = useState("");
  const [loading, setLoading] = useState(false);
  const [uploading, setUploading] = useState(false);
  const [uploadStatus, setUploadStatus] = useState("");
  const fileInputRef = useRef<HTMLInputElement>(null);

  async function sendQuery() {
    const query = input.trim();

    if (!query || loading) {
      return;
    }

    setMessages((previous) => [
      ...previous,
      { role: "user", text: query },
    ]);

    setInput("");
    setLoading(true);

    try {
      const token = localStorage.getItem("citymind_token");

      if (!token) {
        throw new Error(
          "Your login session is missing. Please log in again."
        );
      }

      const response = await fetch(
        `${API_BASE}/knowledge-base/ask`,
        {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: `Bearer ${token}`,
          },
          body: JSON.stringify({
            query,
            top_k: 3,
          }),
        }
      );

      const rawData: unknown = await response
        .json()
        .catch(() => ({}));

      const data: ApiResponse =
        typeof rawData === "object" && rawData !== null
          ? (rawData as ApiResponse)
          : {};

      if (!response.ok) {
        throw new Error(
          getErrorMessage(data, response.status)
        );
      }

      const sources: Source[] = Array.isArray(data.sources)
        ? data.sources.filter(
            (source): source is Source =>
              typeof source === "object" &&
              source !== null &&
              !Array.isArray(source)
          )
        : [];

      // Prefer the actual answer generated by Ollama.
      // answer_grounding is only a fallback/status field.
      const answer =
        typeof data.answer === "string"
          ? data.answer
          : typeof data.answer_grounding === "string"
            ? data.answer_grounding
            : typeof data.message === "string"
              ? data.message
              : "";

      const text = answer.trim()
        ? answer
        : sources.length > 0
          ? "Relevant document passages were found, but no answer was returned."
          : "I couldn't find relevant information in the uploaded documents. Try different keywords or upload a relevant PDF.";

      setMessages((previous) => [
        ...previous,
        {
          role: "assistant",
          text,
          sources,
        },
      ]);
    } catch (error: unknown) {
      const message =
        error instanceof Error
          ? error.message
          : "An unexpected error occurred.";

      setMessages((previous) => [
        ...previous,
        {
          role: "assistant",
          text: `Error: ${message}`,
        },
      ]);
    } finally {
      setLoading(false);
    }
  }

  async function uploadPdf(
    event: React.ChangeEvent<HTMLInputElement>
  ) {
    const file = event.target.files?.[0];

    // Allow selecting the same file again later.
    event.target.value = "";

    if (!file || uploading) {
      return;
    }

    if (!file.name.toLowerCase().endsWith(".pdf")) {
      setUploadStatus("Please select a PDF file.");
      return;
    }

    setUploading(true);
    setUploadStatus("");

    try {
      const token = localStorage.getItem("citymind_token");

      if (!token) {
        throw new Error(
          "Your login session is missing. Please log in again."
        );
      }

      const formData = new FormData();
      formData.append("file", file);

      const response = await fetch(
        `${API_BASE}/knowledge-base/upload`,
        {
          method: "POST",
          headers: {
            Authorization: `Bearer ${token}`,
          },
          body: formData,
        }
      );

      const rawData: unknown = await response
        .json()
        .catch(() => ({}));

      const data: UploadResponse =
        typeof rawData === "object" && rawData !== null
          ? (rawData as UploadResponse)
          : {};

      if (!response.ok) {
        throw new Error(
          getErrorMessage(data as ApiResponse, response.status)
        );
      }

      setUploadStatus(
        `Upload successful: ${data.filename ?? file.name} — ${
          data.chunks_indexed ?? 0
        } text chunks indexed.`
      );

      setMessages((previous) => [
        ...previous,
        {
          role: "assistant",
          text:
            `I've indexed ${data.filename ?? file.name}. ` +
            "You can now ask questions about its contents.",
        },
      ]);
    } catch (error: unknown) {
      const message =
        error instanceof Error
          ? error.message
          : "An unexpected upload error occurred.";

      setUploadStatus(`Upload failed: ${message}`);
    } finally {
      setUploading(false);
    }
  }

  return (
    <div className="flex min-h-screen">
      <Sidebar />

      <main className="flex h-screen min-w-0 max-w-3xl flex-1 flex-col p-4 sm:p-8">
        <div className="mb-5 flex items-start justify-between gap-4">
          <div>
            <h1 className="mb-1 text-xl font-semibold">
              AI Assistant
            </h1>

            <p className="text-sm text-slate-400">
              Ask questions about uploaded knowledge-base documents.
              Answers are generated by Ollama from relevant passages,
              with supporting sources displayed below.
            </p>
          </div>

          <div>
            <input
              ref={fileInputRef}
              type="file"
              accept=".pdf,application/pdf"
              className="hidden"
              onChange={uploadPdf}
              disabled={uploading}
              aria-label="Choose a PDF document"
            />

            <button
              type="button"
              onClick={() => fileInputRef.current?.click()}
              disabled={uploading}
              className="shrink-0 rounded-lg border border-[#00D4FF]/50 px-4 py-2 text-sm text-[#00D4FF] hover:bg-[#00D4FF]/10 disabled:opacity-50"
            >
              {uploading ? "Uploading…" : "Upload PDF"}
            </button>
          </div>
        </div>

        {uploadStatus && (
          <p
            role="status"
            className="mb-4 rounded-lg border border-white/10 bg-white/[0.03] p-3 text-sm text-slate-300"
          >
            {uploadStatus}
          </p>
        )}

        <div
          className="mb-4 flex-1 space-y-4 overflow-y-auto"
          aria-live="polite"
          aria-busy={loading}
        >
          {messages.map((message, index) => (
            <div
              key={index}
              className={
                message.role === "user" ? "text-right" : ""
              }
            >
              <div
                className={`inline-block max-w-[95%] rounded-xl border px-4 py-3 text-left text-sm ${
                  message.role === "user"
                    ? "border-transparent bg-[#00D4FF]/10 text-[#00D4FF]"
                    : "border-white/10 bg-white/[0.03] text-slate-300"
                }`}
              >
                <p className="whitespace-pre-wrap">
                  {message.text}
                </p>

                {message.sources &&
                  message.sources.length > 0 && (
                    <div className="mt-4 space-y-3">
                      <h2 className="text-xs font-semibold uppercase tracking-wide text-[#00D4FF]">
                        Retrieved sources
                      </h2>

                      {message.sources.map(
                        (source, sourceIndex) => (
                          <div
                            key={`${source.document_id ?? "doc"}-${
                              source.chunk_index ?? sourceIndex
                            }-${sourceIndex}`}
                            className="border-l-2 border-[#00D4FF]/40 pl-3 text-xs text-slate-400"
                          >
                            <p className="mb-1 font-medium text-slate-300">
                              Source {sourceIndex + 1}
                              {source.filename
                                ? ` · ${source.filename}`
                                : ""}
                              {source.document_id != null
                                ? ` · Document ${source.document_id}`
                                : ""}
                              {source.page_number != null
                                ? ` · Page ${source.page_number}`
                                : ""}
                              {source.chunk_index != null
                                ? ` · Chunk ${source.chunk_index}`
                                : ""}
                            </p>

                            <p className="whitespace-pre-wrap">
                              {typeof source.excerpt === "string"
                                ? source.excerpt
                                : JSON.stringify(source)}
                            </p>

                            {typeof source.relevance_score ===
                              "number" && (
                              <p className="mt-1 text-slate-500">
                                Relevance score:{" "}
                                {source.relevance_score}
                              </p>
                            )}
                          </div>
                        )
                      )}
                    </div>
                  )}
              </div>
            </div>
          ))}

          {loading && (
            <p className="text-xs text-slate-500">
              Searching documents and generating an answer…
            </p>
          )}
        </div>

        <form
          className="flex gap-3"
          onSubmit={(event) => {
            event.preventDefault();
            void sendQuery();
          }}
        >
          <input
            value={input}
            onChange={(event) => setInput(event.target.value)}
            placeholder="Ask about planning guidelines, traffic rules…"
            aria-label="Ask the CityMind assistant"
            disabled={loading}
            className="min-w-0 flex-1 rounded-lg border border-white/10 bg-white/5 px-4 py-2.5 text-sm focus:border-[#00D4FF]/50 focus:outline-none"
          />

          <button
            type="submit"
            disabled={loading || !input.trim()}
            className="rounded-lg bg-[#00D4FF] px-5 py-2.5 text-sm font-medium text-[#09111f] disabled:opacity-40"
          >
            {loading ? "Asking…" : "Ask"}
          </button>
        </form>
      </main>
    </div>
  );
}